'use client'

import Link from 'next/link'
import { ArrowLeft } from 'lucide-react'
import { useLingui } from '@lingui/react/macro'
import { useLanguage } from '@/components/i18n-provider'
import { LanguageSwitcher } from '@/components/language-switcher'
import { PrintButton } from '@/components/print-button'
import { khr, usd } from '@/lib/utils'

type ReportEntry = {
  recordId: string
  remark: string
  priceUsd: string
  priceKhr: string
  date: string
}

export function PrintReport({
  vehicle,
  owner,
  exportedAt,
  entries,
  totals,
}: {
  vehicle: { name: string; plateNumber: string | null }
  owner: string
  exportedAt: string
  entries: ReportEntry[]
  totals: { usd: number; khr: number }
}) {
  const { t } = useLingui()
  const { locale } = useLanguage()
  const dateRowSpans = new Map<string, number>()
  for (const item of entries) dateRowSpans.set(item.date, (dateRowSpans.get(item.date) ?? 0) + 1)

  return (
    <main className="print-page">
      <div className="print-toolbar">
        <Link href="/" className="button quiet">
          <ArrowLeft size={16} /> {t`Back to overview`}
        </Link>
        <LanguageSwitcher />
        <PrintButton />
      </div>
      <div className="print-sheet">
        <div className="print-brand">
          MOTIVE <span>· {t`VEHICLE CARE`}</span>
        </div>
        <h1>{t`Maintenance report`}</h1>
        <p className="print-subtitle">{t`A complete service record for this vehicle.`}</p>
        <div className="print-meta">
          <div>
            <span>{t`VEHICLE`}</span>
            <strong>{vehicle.name}</strong>
          </div>
          <div>
            <span>{t`PLATE NUMBER`}</span>
            <strong>{vehicle.plateNumber || '—'}</strong>
          </div>
          <div>
            <span>{t`OWNER`}</span>
            <strong>{owner}</strong>
          </div>
          <div>
            <span>{t`EXPORTED`}</span>
            <strong>{exportedAt}</strong>
          </div>
        </div>
        <table className="report-table">
          <thead>
            <tr>
              <th>#</th>
              <th>{t`Date`}</th>
              <th>{t`Maintenance remark / part`}</th>
              <th>{t`Price`} USD ($)</th>
              <th>{t`Price`} KHR (៛)</th>
            </tr>
          </thead>
          <tbody>
            {entries.map((item, index) => {
              const firstForDate = index === 0 || entries[index - 1].date !== item.date
              return (
                <tr key={`${item.recordId}-${index}`}>
                  <td>{String(index + 1).padStart(2, '0')}</td>
                  {firstForDate && (
                    <td style={{ verticalAlign: 'top' }} rowSpan={dateRowSpans.get(item.date) ?? 1}>
                      {item.date}
                    </td>
                  )}
                  <td>{item.remark}</td>
                  <td>{usd(Number(item.priceUsd), locale)}</td>
                  <td>{khr(Number(item.priceKhr), locale)}</td>
                </tr>
              )
            })}
            {!entries.length && (
              <tr>
                <td colSpan={5} className="report-empty">
                  {t`No maintenance entries recorded yet.`}
                </td>
              </tr>
            )}
            <tr className="report-total">
              <td colSpan={3}>{t`GRAND TOTAL`}</td>
              <td>{usd(totals.usd, locale)}</td>
              <td>{khr(totals.khr, locale)}</td>
            </tr>
          </tbody>
        </table>
        <div className="print-foot">{t`Generated by Motive · Private vehicle care`}</div>
      </div>
    </main>
  )
}
